const GITIGNORE_CONTENT = `# Autogenerated by asdlc telemetry: ignore local friction logs; keep policy.yaml
events.jsonl
*.log
`;

/**
 * Records an immutable lifecycle/gate telemetry event into .sdlc/events.jsonl.
 * Fail-silent contract: Any I/O error is swallowed; never throws and never affects command execution.
 */
export function recordEvent(type, payload = {}, { repoRoot = process.cwd() } = {}) {
  try {
    if (!repoRoot || typeof repoRoot !== 'string') return;
    const sdlcDir = path.join(repoRoot, '.sdlc');
    if (!fs.existsSync(sdlcDir)) {
      fs.mkdirSync(sdlcDir, { recursive: true });
    }

    // Physical anti-leak defense: automatically ensure .sdlc/.gitignore exists
    const gitignorePath = path.join(sdlcDir, '.gitignore');
    if (!fs.existsSync(gitignorePath)) {
      try {
        fs.writeFileSync(gitignorePath, GITIGNORE_CONTENT, 'utf8');
      } catch { /* fail-silent */ }
    } else {
      try {
        const existing = fs.readFileSync(gitignorePath, 'utf8');
        if (!existing.includes('events.jsonl')) {
          fs.appendFileSync(gitignorePath, '\nevents.jsonl\n*.log\n', 'utf8');
        }
      } catch { /* fail-silent */ }
    }

    const event = {
      v: 1,
      ts: new Date().toISOString(),
      stage: payload.stage || 'unknown',
      type,
      change: payload.change || null,
      ...payload,
    };

    const targetFile = path.join(sdlcDir, 'events.jsonl');
    fs.appendFileSync(targetFile, JSON.stringify(event) + '\n', 'utf8');
  } catch {
    // Fail-silent contract: Telemetry failures must never break core workflow
  }
}

/**
 * Safely reads local telemetry events from .sdlc/events.jsonl with optional filters.
 */
export function readLocalEvents(repoRoot, { change = null, stage = null, type = null } = {}) {
  try {
    const targetFile = path.join(repoRoot, '.sdlc', 'events.jsonl');
    if (!fs.existsSync(targetFile)) return [];
    const content = fs.readFileSync(targetFile, 'utf8');
    const lines = content.split(/\r?\n/).filter(Boolean);
    const events = [];
    for (const line of lines) {
      try {
        const ev = JSON.parse(line);
        if (change && ev.change !== change) continue;
        if (stage && ev.stage !== stage) continue;
        if (type && ev.type !== type) continue;
        events.push(ev);
      } catch {
        // skip corrupt lines
      }
    }
    return events;
  } catch {
    return [];
  }
}

/**
 * Derives current verification iteration for a change by scanning local events.
 */
export function getChangeIteration(repoRoot, changeId) {
  try {
    const events = readLocalEvents(repoRoot, { change: changeId, stage: 'verify' });
    const verifySummaries = events.filter((e) => e.type === 'gate.verified');
    return verifySummaries.length + 1;
  } catch {
    return 1;
  }
}

/**
 * Appends Markdown summary to GitHub Actions step summary if running in CI.
 */
export function writeGitHubStepSummary(markdownText) {
  try {
    const summaryFile = process.env.GITHUB_STEP_SUMMARY;
    if (summaryFile && typeof summaryFile === 'string') {
      fs.appendFileSync(summaryFile, `\n${markdownText.trim()}\n`, 'utf8');
    }
  } catch {
    // fail-silent
  }
}

function parseChangeDirTimestamp(dirName) {
  const m = String(dirName).match(/^(\d{4})-?(\d{2})-?(\d{2})/);
  if (m) {
    return new Date(`${m[1]}-${m[2]}-${m[3]}T00:00:00Z`).getTime();
  }
  return null;
}

function calculatePercentile(numbers, p) {
  if (!numbers || numbers.length === 0) return 0;
  const sorted = [...numbers].sort((a, b) => a - b);
  const idx = Math.min(sorted.length - 1, Math.floor((p / 100) * sorted.length));
  return sorted[idx];
}

/**
 * Aggregates 30-day team metrics from permanent Git archives and local friction logs.
 * Zero-extra-server: Works immediately on any clone or CI runner.
 */
export function computeTeamMetrics(repoRoot, { days = 30 } = {}) {
  const cutoffMs = Date.now() - (Number(days) * 24 * 60 * 60 * 1000);
  const archiveBase = path.join(openspecDir(repoRoot), 'changes', 'archive');

  const trackedChanges = [];
  const riskLevels = { L0: 0, L1: 0, L2: 0, L3: 0, unlevelled: 0 };
  const specLeadTimesMin = [];
  const implLeadTimesMin = [];
  const convergenceRounds = { r1: 0, r2: 0, r3: 0, escalated: 0 };

  if (fs.existsSync(archiveBase)) {
    let entries = [];
    try {
      entries = fs.readdirSync(archiveBase, { withFileTypes: true });
    } catch { entries = []; }

    for (const ent of entries) {
      if (!ent.isDirectory()) continue;
      const cdir = path.join(archiveBase, ent.name);
      const stampMs = parseChangeDirTimestamp(ent.name);

      let dirTime = stampMs;
      if (!dirTime) {
        try {
          const st = fs.statSync(cdir);
          dirTime = Math.max(st.mtimeMs, st.birthtimeMs);
        } catch { dirTime = 0; }
      }

      if (dirTime && dirTime < cutoffMs) continue;

      trackedChanges.push(ent.name);

      // 1. Risk Tier breakdown
      const metaPath = path.join(cdir, '.openspec.yaml');
      let lvl = 'unlevelled';
      if (exists(metaPath)) {
        try {
          const meta = readYaml(metaPath) ?? {};
          if (meta.level) {
            lvl = String(meta.level).toUpperCase();
          }
        } catch {}
      }
      if (riskLevels[lvl] !== undefined) riskLevels[lvl] += 1;
      else riskLevels.unlevelled += 1;

      // 2. Lead Time Calculation
      let tStart = null;
      let tApprove = null;
      let tArchive = dirTime;

      // Check intake index for start timestamp
      const intakePath = path.join(cdir, 'intake', 'index.yaml');
      if (exists(intakePath)) {
        try {
          const intake = readYaml(intakePath);
          if (intake?.capturedAt) tStart = new Date(intake.capturedAt).getTime();
        } catch {}
      }

      // Check review.md for approval timestamp
      const reviewPath = path.join(cdir, 'review.md');
      let reviewText = '';
      if (exists(reviewPath)) {
        try {
          reviewText = readText(reviewPath);
          const m = reviewText.match(/-\s*approvedAt\s*:\s*['"]?([^\s'"]+)['"]?/i);
          if (m) tApprove = new Date(m[1]).getTime();
        } catch {}
      }

      if (!tStart && exists(path.join(cdir, 'proposal.md'))) {
        try {
          const st = fs.statSync(path.join(cdir, 'proposal.md'));
          tStart = st.birthtimeMs || st.mtimeMs;
        } catch {}
      }

      if (tStart && tApprove && tApprove >= tStart) {
        specLeadTimesMin.push(Math.round((tApprove - tStart) / 60000));
      }
      if (tApprove && tArchive && tArchive >= tApprove) {
        implLeadTimesMin.push(Math.round((tArchive - tApprove) / 60000));
      }

      // 3. Autonomous PR convergence estimation
      if (/asdlc:needs-human-arbitration/i.test(reviewText)) {
        convergenceRounds.escalated += 1;
      } else {
        const trailerMatches = (reviewText.match(/\(ref:\s*#PRRT_[^)]+\)/g) || []).length;
        if (trailerMatches === 0) convergenceRounds.r1 += 1;
        else if (trailerMatches === 1) convergenceRounds.r2 += 1;
        else convergenceRounds.r3 += 1;
      }
    }
  }

  // 4. Local Friction Ranking from .sdlc/events.jsonl
  const localEvents = readLocalEvents(repoRoot, { stage: 'verify' });
  const lintEvents = readLocalEvents(repoRoot, { stage: 'lint' });
  const allFails = [...localEvents, ...lintEvents].filter((e) => e.type === 'gate.evaluated' && e.status === 'fail');

  const gateFailMap = new Map();
  for (const ev of allFails) {
    const key = `${ev.gate || 'unknown'}|${ev.stage || 'verify'}`;
    const curr = gateFailMap.get(key) || { gate: ev.gate || 'unknown', stage: ev.stage || 'verify', count: 0, sampleDetail: ev.detail || '' };
    curr.count += 1;
    if (ev.detail && ev.detail.length > 5) curr.sampleDetail = ev.detail;
    gateFailMap.set(key, curr);
  }

  const frictionLeaderboard = [...gateFailMap.values()].sort((a, b) => b.count - a.count).slice(0, 5);

  const total = trackedChanges.length;
  const r1Pct = total > 0 ? Math.round((convergenceRounds.r1 / total) * 100) : 100;
  const r2Pct = total > 0 ? Math.round((convergenceRounds.r2 / total) * 100) : 0;
  const r3Pct = total > 0 ? Math.round((convergenceRounds.r3 / total) * 100) : 0;
  const escPct = total > 0 ? Math.round((convergenceRounds.escalated / total) * 100) : 0;

  return {
    days,
    totalTrackedChanges: total,
    riskLevels,
    leadTime: {
      specP50Min: calculatePercentile(specLeadTimesMin, 50),
      specP90Min: calculatePercentile(specLeadTimesMin, 90),
      implP50Min: calculatePercentile(implLeadTimesMin, 50),
      implP90Min: calculatePercentile(implLeadTimesMin, 90),
    },
    convergence: {
      r1Pct,
      r2Pct,
      r3Pct,
      escPct,
      counts: convergenceRounds,
    },
    frictionLeaderboard,
  };
}

/**
 * Formats team metrics into clean ANSI ASCII tables matching Section 7.1.
 */
export function renderMetricsDashboard(metrics) {
  const lines = [];
  lines.push('======================= 🏛️ ASDLC HARNESS OBSERVABILITY =======================');
  lines.push(`📅 Data Source: Git Archive History (Last ${metrics.days} Days, ${metrics.totalTrackedChanges} changes tracked)`);
  lines.push('');

  lines.push('1. 🚦 Gate Friction Leaderboard (Local .sdlc/ Retries)');
  lines.push('   Rank | Gate                  | Stage  | Fails | Top Failure Pattern');
  lines.push('   --------------------------------------------------------------------------');
  if (metrics.frictionLeaderboard.length === 0) {
    lines.push('   (No local gate failures recorded)');
  } else {
    metrics.frictionLeaderboard.forEach((item, idx) => {
      const rank = `#${idx + 1}`.padEnd(4, ' ');
      const gate = item.gate.padEnd(21, ' ').slice(0, 21);
      const stage = item.stage.padEnd(6, ' ');
      const fails = String(item.count).padEnd(5, ' ');
      const sample = String(item.sampleDetail || 'check failed').slice(0, 32);
      lines.push(`   ${rank} | ${gate} | ${stage} | ${fails} | ${sample}`);
    });
  }
  lines.push('');

  lines.push('2. 🔄 Autonomous PR Convergence (3-Round Cap)');
  lines.push(`   • Round 1 Pass (Zero rework)    : ${metrics.convergence.r1Pct}% (${metrics.convergence.counts.r1} PRs)`);
  lines.push(`   • Round 2 Pass (Converged Rd 2) : ${metrics.convergence.r2Pct}% (${metrics.convergence.counts.r2} PRs)`);
  lines.push(`   • Round 3 Pass (Converged Rd 3) : ${metrics.convergence.r3Pct}% (${metrics.convergence.counts.r3} PRs)`);
  lines.push(`   • Human Escalated (>3 rounds)   : ${metrics.convergence.escPct}% (${metrics.convergence.counts.escalated} PRs)`);
  lines.push('');

  lines.push('3. ⏱️ Stage Lead Time (P50 / P90 via Git Provenance)');
  lines.push(`   • Stage new -> approve (Spec Phase): ${metrics.leadTime.specP50Min}m / ${metrics.leadTime.specP90Min}m`);
  lines.push(`   • Stage apply -> verify (TDD Phase): ${metrics.leadTime.implP50Min}m / ${metrics.leadTime.implP90Min}m`);
  lines.push('');

  const l0 = metrics.riskLevels.L0 || 0;
  const l1 = metrics.riskLevels.L1 || 0;
  const l2 = metrics.riskLevels.L2 || 0;
  const l3 = metrics.riskLevels.L3 || 0;
  lines.push('4. 🛡️ Risk Tier Breakdown');
  lines.push(`   • L0 (Docs/Internal): ${l0} | L1 (Normal): ${l1} | L2 (High): ${l2} | L3 (Critical): ${l3}`);
  lines.push('=============================================================================');

  return lines.join('\n');
}
