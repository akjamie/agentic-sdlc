import path from 'node:path';
import { exists, writeText } from '../lib/fs.js';
import { changeDir } from '../lib/paths.js';
import { requireRepo, toChangeSlug } from '../lib/cliutil.js';
import { ensureGraphify, ensureFreshGraph, graphifyQuery } from '../lib/graphify.js';
import { runOpenspec } from '../lib/openspec.js';
import { runShell } from '../lib/exec.js';
import { fail } from '../lib/errors.js';
import { log } from '../lib/log.js';

// STAGE 1 of the spec (v10: explore + propose are ONE step).
//   1) scaffold the change through OpenSpec
//   2) refresh the knowledge graph (graphify, behind the scenes)
//   3) write explore.md so the proposal is grounded in the real system
export function newChange(changeId, opts = {}) {
  const repoRoot = requireRepo(opts);
  const slug = toChangeSlug(changeId);
  const cdir = changeDir(repoRoot, slug);
  if (exists(cdir)) fail(`change '${slug}' already exists`, { hint: 'use a new id, or iterate the existing change' });

  const res = runOpenspec(['new', 'change', slug], repoRoot);
  if (res.missing) fail('OpenSpec CLI not found', { hint: 'run `asdlc init`' });
  if (res.status !== 0) fail(`openspec new change failed: ${(res.stderr || res.stdout || '').slice(0, 300)}`);
  log.ok(`created change '${slug}'`);

  const g = ensureGraphify();
  if (!g.installed) {
    log.warn('graphify not installed (need uv/pip + your internal mirror); explore.md skipped');
  } else {
    const fresh = ensureFreshGraph(repoRoot);
    const q = opts.query ?? slug;
    const hubs = (runShell('graphify god-nodes', repoRoot).stdout || '').trim();
    const query = graphifyQuery(repoRoot, q);
    const md = `# Explore: ${changeId}

> Generated by \`asdlc new\` from the knowledge graph - structured queries, not
> code reading. Ground the proposal in this. generatedAt: ${new Date().toISOString()}

## Architectural hubs (god nodes)

${hubs || '_(none)_'}

## Query: ${q}

${(query.stdout || '').trim() || '_(no matches)_'}
`;
    writeText(path.join(cdir, 'explore.md'), md);
    log.ok(`wrote explore.md (graph ${fresh.status})`);
  }

  // Seed the grilling interview (skill: grilling / grill-me). The agent runs it
  // with the author and records settled decisions here BEFORE writing the spec.
  const clar = path.join(cdir, 'clarifications.md');
  if (!exists(clar)) {
    writeText(clar, `# Clarifications: ${changeId}

> Before writing proposal.md / specs, the agent MUST run a **grilling** interview
> with the author (skill: \`grilling\`) and record the settled decisions here.
> Grilling works the design as a tree, in rounds: ask the whole FRONTIER - every
> decision whose prerequisites are settled - number each question, and give your
> recommended answer. Facts are the agent's job to look up; decisions are the
> author's to make. The spec is ready to write when the frontier is empty.

## Settled decisions
<!-- one entry per settled decision: decision -> answer, with the reason -->

## Open questions
<!-- must be empty before the spec is written -->
`);
    log.ok('seeded clarifications.md (run the grilling interview)');
  }

  log.info('');
  log.info('Next:');
  log.info(`  1. grill the author (skill: grilling) and fill clarifications.md`);
  log.info('  2. author proposal.md -> specs/** -> review.md, grounded in explore.md');
  log.info(`  3. asdlc lint ${changeId}`);
  return slug;
}

export function register(program) {
  program
    .command('new <changeId>')
    .description('start a spec: scaffold + refresh the graph + explore.md + clarifications.md (for grilling)')
    .option('--query <q>', 'graph query terms (default: the change id)')
    .option('--repo-root <path>')
    .action((changeId, opts) => {
      newChange(changeId, opts);
    });
}
