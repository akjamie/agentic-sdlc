test('Semantics: Layer 1 Java/Spring & Alibaba signatures', () => {
  // 1. Spring Security -> L3
  const secJava = `
    package com.example.security;
    import org.springframework.security.config.annotation.web.builders.HttpSecurity;
    public class CustomSecurityConfig {}
  `;
  const secRes = scanImports('src/main/java/com/example/security/CustomConfig.java', secJava);
  assert.equal(secRes?.level, 'L3');
  assert.equal(secRes?.mandatoryHumanReview, true);

  // 2. Dubbo RPC -> L2
  const dubboJava = `
    package com.example.order;
    import org.apache.dubbo.config.annotation.DubboService;
    @DubboService
    public class OrderServiceImpl implements OrderService {}
  `;
  const dubboRes = scanImports('src/main/java/com/example/order/OrderServiceImpl.java', dubboJava);
  assert.equal(dubboRes?.level, 'L2');

  // 3. MyBatis XML: pure select -> L1, write/update -> L2
  const xmlSelect = `
    <?xml version="1.0" encoding="UTF-8" ?>
    <!DOCTYPE mapper PUBLIC "-//mybatis.org//DTD Mapper 3.0//EN" "http://mybatis.org/dtd/mybatis-3-mapper.dtd">
    <mapper namespace="com.example.mapper.UserMapper">
      <select id="findById" resultType="com.example.User">SELECT * FROM users WHERE id = #{id}</select>
    </mapper>
  `;
  const selectRes = scanSchemaHeaders('src/main/resources/mapper/UserMapper.xml', xmlSelect);
  assert.equal(selectRes?.level, 'L1', 'Pure select query must remain L1 routine');

  const xmlUpdate = `
    <mapper namespace="com.example.mapper.UserMapper">
      <update id="updateBalance">UPDATE accounts SET balance = balance - #{amount} WHERE id = #{id}</update>
    </mapper>
  `;
  const updateRes = scanSchemaHeaders('src/main/resources/mapper/UserMapper.xml', xmlUpdate);
  assert.equal(updateRes?.level, 'L2');
});

test('Semantics: Layer 1 Go signatures, generated code exclusion, and paired down.sql', () => {
  // 1. Go JWT -> L3
  const goJwt = `
    package auth
    import (
      "fmt"
      "github.com/golang-jwt/jwt/v5"
    )
  `;
  const goJwtRes = scanImports('internal/auth/token.go', goJwt);
  assert.equal(goJwtRes?.level, 'L3');
  assert.equal(goJwtRes?.mandatoryHumanReview, true);

  // 2. Go Gin Routing -> L2
  const goGin = `
    package handler
    import "github.com/gin-gonic/gin"
  `;
  const goGinRes = scanImports('pkg/api/handler.go', goGin);
  assert.equal(goGinRes?.level, 'L2');

  // 3. Generated code exclusion & anti-gaming
  const pbGo = `// Code generated by protoc-gen-go. DO NOT EDIT.
// source: order.proto
package v1
import "google.golang.org/grpc"
`;
  assert.equal(isGeneratedFile('api/v1/order.pb.go', pbGo), true);
  const genAnalysis = analyzeFileSemantics({ filePath: 'api/v1/order.pb.go', content: pbGo });
  assert.equal(genAnalysis.isGenerated, true);
  assert.equal(genAnalysis.level, 'L1');

  // Anti-gaming: self-declared marker in arbitrary source file cannot suppress risk
  const fakeGen = `// Code generated DO NOT EDIT.\nimport passport from "passport";`;
  assert.equal(isGeneratedFile('src/auth.js', fakeGen), false, 'Arbitrary files cannot game generated file exclusion');
  const fakeAnalysis = analyzeFileSemantics({ filePath: 'src/auth.js', content: fakeGen });
  assert.equal(fakeAnalysis.isGenerated, false);
  assert.equal(fakeAnalysis.level, 'L3', 'Security imports in unverified paths must escalate to L3');

  // 4. Paired down.sql vs standalone down.sql
  const dropSql = `DROP TABLE users;`;
  const pairedDown = scanSchemaHeaders('migrations/001_create_users.down.sql', dropSql, {
    allChangedFiles: ['migrations/001_create_users.up.sql', 'migrations/001_create_users.down.sql']
  });
  assert.equal(pairedDown?.level, 'L2', 'Paired down.sql with up.sql in the same PR is L2, not L3');

  const standaloneDown = scanSchemaHeaders('migrations/001_create_users.down.sql', dropSql, {
    allChangedFiles: ['migrations/001_create_users.down.sql']
  });
  assert.equal(standaloneDown?.level, 'L3', 'Standalone down.sql modifying history is L3');
});

test('Semantics: Layer 1 Python & Node.js signatures and frontend client noise reduction', () => {
  // 1. Python FastAPI Security -> L3
  const pySec = `from fastapi.security import OAuth2PasswordBearer\noauth2_scheme = OAuth2PasswordBearer(tokenUrl="token")`;
  assert.equal(scanImports('app/deps.py', pySec)?.level, 'L3');

  // 2. Python Alembic Destructive -> L3 vs Non-Destructive -> L2
  const pyAlembicDestructive = `from alembic import op\ndef upgrade():\n    op.drop_table('legacy_orders')`;
  assert.equal(scanImports('alembic/versions/123_migration.py', pyAlembicDestructive)?.level, 'L3');

  const pyAlembicAdd = `from alembic import op\ndef upgrade():\n    op.create_table('new_orders')`;
  assert.equal(scanImports('alembic/versions/123_migration.py', pyAlembicAdd)?.level, 'L2');

  // 3. Node.js Frontend Client (import axios) stays L1
  const frontendClient = `import axios from 'axios';\nexport const fetchUsers = () => axios.get('/api/users');`;
  const feRes = scanImports('src/api/client.ts', frontendClient);
  assert.equal(feRes, null, 'Pure frontend axios client must produce no server contract signal');

  // 4. Node.js Next.js root middleware -> L3; non-root middleware -> L1
  const middleware = `export function middleware(request) { return Response.next(); }`;
  assert.equal(scanImports('src/middleware.ts', middleware)?.level, 'L3');
  assert.equal(scanImports('middleware.js', middleware)?.level, 'L3');
  assert.equal(scanImports('packages/lib/middleware.ts', middleware), null, 'Non-root middleware.ts must not trigger L3');
});

test('Semantics: Multi-line YAML manifests, deleted contracts, and engine performance', () => {
  // 1. Multi-line Kubernetes manifest
  const k8sDeployment = `apiVersion: apps/v1
kind: Deployment
metadata:
  name: nginx-deployment
spec:
  replicas: 3
`;
  const k8sRes = scanSchemaHeaders('deploy/web.yaml', k8sDeployment);
  assert.equal(k8sRes?.level, 'L2');
  assert.equal(k8sRes?.id, 'SEM_K8S_MANIFEST');

  // 2. Multi-line Serverless Devs manifest
  const serverlessDevs = `edition: 3.0.0
name: hello-world-app
access: default
services:
  app:
    component: fc3
`;
  const sRes = scanSchemaHeaders('s.yaml', serverlessDevs);
  assert.equal(sRes?.level, 'L2');
  assert.equal(sRes?.id, 'SEM_SERVERLESS_DEVS');

  // 3. Bidirectional deletion: deleted pom.xml and deleted router escalate to L2
  const deletedPom = analyzeFileSemantics({
    filePath: 'pom.xml',
    content: null,
    oldContent: '<project xmlns="http://maven.apache.org/POM/4.0.0"><modelVersion>4.0.0</modelVersion></project>'
  });
  assert.equal(deletedPom.level, 'L2', 'Deleting build manifest pom.xml must escalate to L2');

  const deletedController = analyzeFileSemantics({
    filePath: 'src/main/java/com/example/OrderController.java',
    content: null,
    oldContent: '@RestController public class OrderController {}'
  });
  assert.equal(deletedController.level, 'L2', 'Deleting server controller must escalate to L2');

  // 4. Pure engine execution time < 50ms across 50 files
  const sampleContent = 'import express from "express"; const app = express(); app.get("/health", (req, res) => res.send("ok"));';
  const t0 = performance.now();
  for (let i = 0; i < 50; i++) {
    analyzeFileSemantics({ filePath: `src/routes/handler_${i}.js`, content: sampleContent });
  }
  const elapsed = performance.now() - t0;
  assert.ok(elapsed < 50, `Semantics engine must complete 50 files in <50ms (measured: ${elapsed.toFixed(2)}ms)`);
});

test('Semantics: L1 Bounded Positive Safety Envelope and De-lexiconization', () => {
  // 1. Bounded local code (<= 5 production files) stays L1
  const assessedL1 = assess({
    stage: 'impl',
    requirement: 'update tax calculation and discount rules',
    changedFiles: ['src/services/tax.js', 'src/services/discount.js'],
    persist: false
  });
  assert.equal(assessedL1.risk.level, 'L1', 'Bounded local code <= 5 files stays L1');

  // 2. Unbounded local code (> 5 production files) escalates to L2
  const assessedUnbounded = assess({
    stage: 'impl',
    requirement: 'mass refactoring across components',
    changedFiles: [
      'src/comp1.js',
      'src/comp2.js',
      'src/comp3.js',
      'src/comp4.js',
      'src/comp5.js',
      'src/comp6.js'
    ],
    persist: false
  });
  assert.equal(assessedUnbounded.risk.level, 'L2', 'Touching > 5 production files escalates to L2');

  // 3. Root export entrypoint (index.ts) escalates to L2
  const assessedEntrypoint = assess({
    stage: 'impl',
    requirement: 'export new utility from entrypoint',
    changedFiles: ['src/index.ts'],
    persist: false
  });
  assert.equal(assessedEntrypoint.risk.level, 'L2', 'Touching root export index.ts escalates to L2');
});

